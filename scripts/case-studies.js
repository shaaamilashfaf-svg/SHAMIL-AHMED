/**
 * Initializes the Interactive Case Study Modal
 */
export function initCaseStudyModal() {
  const modalBackdrop = document.getElementById('caseStudyModal');
  const modalContainer = document.getElementById('caseStudyContent');
  
  if (!modalBackdrop) return;

  function renderModal(index) {
    const project = caseStudies[index];
    if (!project) return;

    const nextIndex = (index + 1) % caseStudies.length;
    const prevIndex = (index - 1 + caseStudies.length) % caseStudies.length;

    modalContainer.innerHTML = `
      <div class="case-modal-header">
        <div class="modal-title-meta">
          <span class="modal-project-num">Project ${project.number} / 04</span>
          <h2 class="modal-project-name">${project.title}</h2>
        </div>
        <button class="modal-close-btn" id="modalCloseAction" aria-label="Close Case Study">✕</button>
      </div>

      <div class="case-modal-body">
        <div class="modal-hero-image-wrap">
          <img src="${project.image}" alt="${project.title} UI/UX Case Study Mockup" />
        </div>

        <div class="modal-meta-grid">
          <div class="modal-meta-item">
            <h4>Role</h4>
            <p>${project.role.split('(')[0]}</p>
          </div>
          <div class="modal-meta-item">
            <h4>Timeline</h4>
            <p>${project.year}</p>
          </div>
          <div class="modal-meta-item">
            <h4>Category</h4>
            <p>${project.category}</p>
          </div>
          <div class="modal-meta-item">
            <h4>Primary Tools</h4>
            <p>${project.tools.slice(0, 3).join(', ')}</p>
          </div>
        </div>

        <div class="modal-section-block">
          <span class="section-eyebrow">Project Overview</span>
          <h3>${project.tagline}</h3>
          <p>${project.overview}</p>
        </div>

        <div class="modal-section-block">
          <span class="section-eyebrow">The Challenge & UX Solution</span>
          <p><strong>The Challenge:</strong> ${project.challenge}</p>
          <p><strong>The Solution:</strong> ${project.solution}</p>
        </div>

        <div class="modal-section-block">
          <span class="section-eyebrow">Key Features & Architecture</span>
          <div class="modal-features-grid">
            ${project.keyDeliverables.map(item => `
              <div class="modal-feature-card">
                <h5>${item.title}</h5>
                <p>${item.desc}</p>
              </div>
            `).join('')}
          </div>
        </div>

        <div class="modal-section-block">
          <span class="section-eyebrow">Design Decisions & Impact</span>
          <div class="modal-meta-grid">
            <div class="modal-meta-item">
              <h4>Typography Direction</h4>
              <p>${project.designDecisions.typography}</p>
            </div>
            <div class="modal-meta-item">
              <h4>Palette System</h4>
              <p>${project.designDecisions.colors}</p>
            </div>
            <div class="modal-meta-item">
              <h4>Outcome / Metric</h4>
              <p style="color: var(--accent); font-weight: 800;">${project.designDecisions.metrics}</p>
            </div>
          </div>
        </div>
      </div>

      <div class="modal-footer-nav">
        <button class="btn btn-secondary" id="prevProjectBtn">
          ← ${caseStudies[prevIndex].title}
        </button>
        <a href="#contact" class="btn btn-primary" id="modalStartProject">
          Start Similar Project ↗
        </a>
        <button class="btn btn-secondary" id="nextProjectBtn">
          ${caseStudies[nextIndex].title} →
        </button>
      </div>
    `;

    // Reattach listeners
    document.getElementById('modalCloseAction')?.addEventListener('click', closeModal);
    document.getElementById('prevProjectBtn')?.addEventListener('click', () => renderModal(prevIndex));
    document.getElementById('nextProjectBtn')?.addEventListener('click', () => renderModal(nextIndex));
    document.getElementById('modalStartProject')?.addEventListener('click', () => {
      closeModal();
    });
  }

  function openModal(index) {
    renderModal(index);
    modalBackdrop.classList.add('active');
    document.body.style.overflow = 'hidden';
  }

  function closeModal() {
    modalBackdrop.classList.remove('active');
    document.body.style.overflow = '';
  }

  // Trigger buttons
  document.querySelectorAll('[data-case-study]').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const projectIndex = parseInt(btn.getAttribute('data-case-study'), 10);
      openModal(projectIndex);
    });
  });

  modalBackdrop.addEventListener('click', (e) => {
    if (e.target === modalBackdrop) closeModal();
  });

  window.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && modalBackdrop.classList.contains('active')) {
      closeModal();
    }
  });
}
